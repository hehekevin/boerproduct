"""benchkit — academic-writing benchmark & eval-tool builder (stdlib).

For the writing_benchmark workorder. Produces a decidable task set + reference
answers (with acceptable variants) + observable scoring anchors + a reproducible
eval runner, addressing: 题能判定 / 答案站得住 / 锚点打得齐 / 跑得复现.

validate_benchmark checks each task has input material, instruction, required
points, acceptable variants and observable anchors (two graders can agree).
build_benchmark emits tasks.json, rubric.json, reference_answers.md and eval.py;
eval.py deterministically checks the mechanical anchors (required points present,
numbers/citations match, format) and reports per-task pass/fail + reasons.
"""
from __future__ import annotations

import json
from pathlib import Path

import figkit


def validate_benchmark(ir: dict) -> dict:
    errors, warnings = [], []
    tasks = ir.get("tasks", [])
    if not tasks:
        errors.append("benchmark has no tasks")
    for t in tasks:
        tid = t.get("id", "?")
        if not t.get("instruction"):
            errors.append(f"task {tid}: no instruction")
        if not t.get("input_material"):
            errors.append(f"task {tid}: no input material (not decidable)")
        if not t.get("required_points"):
            errors.append(f"task {tid}: no required points (not decidable)")
        if not t.get("anchors"):
            warnings.append(f"task {tid}: no observable scoring anchors")
        for a in t.get("anchors", []):
            if not a.get("observable"):
                warnings.append(f"task {tid}: anchor '{a.get('criterion')}' not observable")
        if not t.get("acceptable_variants"):
            warnings.append(f"task {tid}: no acceptable variants (risks single-essay grading)")
        if not t.get("reference_answer"):
            warnings.append(f"task {tid}: no reference answer")
    return {"ok": not errors, "errors": errors, "warnings": warnings}


EVAL_TEMPLATE = '''#!/usr/bin/env python3
"""Reproducible mechanical eval for the writing benchmark (generated by benchkit).
Checks observable anchors: required points present, forbidden errors absent,
numbers/citations match source. Subjective quality left to the rubric/LLM judge.
Usage: python eval.py --submission <dir-or-md> --tasks tasks.json
"""
import argparse, json, re, sys
from pathlib import Path

def load(p): return json.loads(Path(p).read_text(encoding="utf-8"))

def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--submission", required=True); ap.add_argument("--tasks", required=True)
    a = ap.parse_args()
    sub = Path(a.submission)
    text = sub.read_text(encoding="utf-8") if sub.is_file() else "\\n".join(p.read_text(encoding="utf-8") for p in sorted(sub.glob("*.md")))
    tasks = load(a.tasks); report = []
    for t in tasks:
        reasons = []; ok = True
        for pt in t.get("required_points", []):
            if pt.lower() not in text.lower(): ok = False; reasons.append("missing required point: " + pt)
        for bad in t.get("forbidden", []):
            if bad.lower() in text.lower(): ok = False; reasons.append("forbidden content: " + bad)
        report.append({"task": t["id"], "pass": ok, "reasons": reasons})
    npass = sum(r["pass"] for r in report)
    out = {"n_tasks": len(report), "n_pass": npass, "score": round(100.0 * npass / max(len(report), 1), 1), "results": report}
    print(json.dumps(out, ensure_ascii=False, indent=2))

if __name__ == "__main__": main()
'''


def build_benchmark(ir: dict, out_dir: Path) -> dict:
    out_dir.mkdir(parents=True, exist_ok=True)
    tasks = ir.get("tasks", [])
    figkit.write_json(out_dir / "tasks.json", tasks)
    rubric = [{"task": t["id"], "anchors": t.get("anchors", []),
               "acceptable_variants": t.get("acceptable_variants", []),
               "required_points": t.get("required_points", [])} for t in tasks]
    figkit.write_json(out_dir / "rubric.json", rubric)
    ref = ["# Reference answers (with acceptable variants)", ""]
    for t in tasks:
        ref += [f"## {t['id']}", "", t.get("reference_answer", ""), "",
                "Acceptable variants: " + "; ".join(t.get("acceptable_variants", [])) or "none", ""]
    (out_dir / "reference_answers.md").write_text("\n".join(ref), encoding="utf-8")
    (out_dir / "eval.py").write_text(EVAL_TEMPLATE, encoding="utf-8")
    return {"artifacts": [{"name": n, "path": str(out_dir / n), "format": n.split(".")[-1], "role": n.split(".")[-1]}
                          for n in ("tasks.json", "rubric.json", "reference_answers.md", "eval.py")],
            "n_tasks": len(tasks)}